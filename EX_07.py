#Receba os valores do comprimento, largura e altura de um paralelpípedo. Calcule e mostre o seu volume

#Declarar

C: int = 0 #Comprimento
L: int = 0 #Largura
H: int = 0 #Altura
Vol: int = 0 #Volume

#Início

C = float(input("Digite o comprimento da figura: "))
L = float(input("Digite a largura da figura: "))
H = float(input("Digite a altura da figura: "))
Vol = (C*L*H)
print (Vol)

